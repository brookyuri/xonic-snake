import type { GameState, PlayerId, Pos } from './types'

/**
 * Раздел 7 GAME_RULES.md. ЗАГЛУШКА для этой сессии: полный алгоритм
 * (BFS по компонентам связности, исключение компоненты с головой
 * противника) не реализован — это следующая сессия.
 *
 * Возвращает только клетки собственного следа игрока (тривиальный случай
 * раздела 7, когда след не отрезал ни одной дополнительной области).
 * Этого достаточно, чтобы выход из дома и возвращение домой уже работали.
 */
export function computeCapture(state: GameState, player: PlayerId): Pos[] {
  return state.players[player].trail.map((p) => ({ ...p }))
}
